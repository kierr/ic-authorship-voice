#!/usr/bin/env python3
"""report_gates.py — compute the definition-of-done numbers mechanically and
rewrite eval/state.md's gate table.

Every computed row is measured from the ledgers against the
corpus gates defined in AGENTS.md on
each run — the previous hand-typed table drifted from the data, so hand
edits to computed rows are forbidden. The two human-graded rows (judge
ranking, operator blind) are carried through verbatim from the existing
state.md; any prose after the table is preserved.

Usage: python3 eval/report_gates.py
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))

import validate_corpus as vc

STATE = os.path.join(ROOT, "eval", "state.md")

# Corpus gate thresholds (see AGENTS.md).
KJ_MIN = 150
PUB_MIN = 8
DECADES_MIN = 2
CONTRAST_MIN = 3

POSITIVE_CLASSES = ("key_judgements", "confidence_statements", "full_assessment")

HUMAN_MARK = "(human-graded — edited by hand only)"
# Carried from the live state.md when present; these frozen copies are the
# fallback only if the rows vanish from the file.
HUMAN_ROWS = (
    ("| judge ranking",
     "| judge ranking (blind) | **FAILED to date** — the blind judge caught "
     "the model 5/5 on a composed-elaboration tell; the gate needs a "
     "terse-DIS task or a larger model |"),
    ("| operator blind",
     "| operator blind (reference, model ≥4/5) | **NOT passed** — same "
     "composed-tell; deck at eval/blind_deck.md (regenerated 2026-08-21 from the clean2 bench) |"),
)

HEADER = [
    "# Definition-of-done report — ic-authorship-voice (v1 status)",
    "",
    "Computed rows are generated by eval/report_gates.py against the corpus "
    "gates in AGENTS.md. "
    "rerun it after any corpus rebuild — never hand-edit them. Rows "
    "marked %s and any prose after the table are the hand-maintained "
    "exceptions." % HUMAN_MARK,
    "",
    "| Gate | Status |",
    "|---|---|",
]


def _met(ok):
    return "**MET**" if ok else "**UNMET**"


def _split_rows(split):
    return vc.read_jsonl(os.path.join(ROOT, "corpus", "%s.jsonl" % split))


def kj_counts():
    """Real key_judgements rows per split."""
    return dict((s, sum(1 for r in _split_rows(s)
                        if r.get("class") == "key_judgements"
                        and r.get("origin") == "real"))
                for s in vc.SPLITS)


def positive_publishers(man):
    pubs = set(vc.norm_publisher(r.get("publisher")) for r in man
               if r.get("status") == "fetched"
               and r.get("class") in POSITIVE_CLASSES)
    pubs.discard("")
    return pubs


def year_stats(man):
    """(min_year, max_year, distinct decades) of fetched positive sources."""
    years = []
    for r in man:
        if r.get("status") != "fetched" or r.get("class") not in POSITIVE_CLASSES:
            continue
        m = re.match(r"(\d{4})", str(r.get("published", "")))
        if m:
            years.append(int(m.group(1)))
    if not years:
        return None
    return min(years), max(years), len(set(y // 10 for y in years))


def licence_stats(man):
    fetched = [r for r in man if r.get("status") == "fetched"]
    present = [r for r in fetched if r.get("licence")]
    placeholder = sum(1 for r in present if r.get("licence") == "check")
    return len(fetched), len(present), placeholder


def contrast_counts():
    counts = {}
    for r in vc.read_jsonl(os.path.join(ROOT, "corpus", "contrast.jsonl")):
        c = r.get("class", "?")
        counts[c] = counts.get(c, 0) + 1
    return counts


def negative_llm_stats():
    rows = vc.read_jsonl(os.path.join(ROOT, "corpus", "negative_llm.jsonl"))
    unlabelled = sum(1 for r in rows if not r.get("dominant_failure"))
    return len(rows), unlabelled


def split_bools():
    """(doc_grouped, publisher_holdout, dirty_val_test_rows)."""
    where, pubs, dirty = {}, {}, 0
    for s in vc.SPLITS:
        pubs[s] = set()
        for r in _split_rows(s):
            sid = r.get("source_id")
            if sid:
                where.setdefault(sid, set()).add(s)
            pubs[s].add(vc.norm_publisher(r.get("publisher")))
            if s in ("val", "test") and (r.get("origin") != "real"
                                         or r.get("qa") != "pass"):
                dirty += 1
    grouped = all(len(x) == 1 for x in where.values())
    holdout = not (pubs["test"] & (pubs["train"] | pubs["val"]))
    return grouped, holdout, dirty


def build_table():
    man = vc.load_manifest()
    ids = [r.get("id") for r in man]
    total, unique = len(ids), len(set(ids))
    fetched = sum(1 for r in man if r.get("status") == "fetched")

    kj = kj_counts()
    kj_total = sum(kj.values())
    pubs = positive_publishers(man)
    ys = year_stats(man)
    verified, empty, mismatched, missing = vc.hash_coverage()
    nfetched, present, placeholder = licence_stats(man)
    cc = contrast_counts()
    nllm, unlabelled = negative_llm_stats()
    grouped, holdout, dirty = split_bools()

    rows = []
    rows.append("| sources registered | %s — %d rows, %d unique ids, %d fetched |"
                % (_met(unique == total), total, unique, fetched))
    rows.append("| ≥%d real KJ items | %s — %d real KJ (train %d / val %d / test %d) |"
                % (KJ_MIN, _met(kj_total >= KJ_MIN), kj_total,
                   kj["train"], kj["val"], kj["test"]))
    rows.append("| ≥%d publishers | %s — %d distinct positive publishers (%s) |"
                % (PUB_MIN, _met(len(pubs) >= PUB_MIN), len(pubs),
                   ", ".join(sorted(pubs))))
    if ys:
        span, dec_ok = "%d-%d, %d decades" % ys, ys[2] >= DECADES_MIN
    else:
        span, dec_ok = "no published years", False
    rows.append("| ≥%d decades | %s — %s |" % (DECADES_MIN, _met(dec_ok), span))
    rows.append("| all hashed | %s — %d verified, %d empty, %d mismatched, "
                "%d raw missing |"
                % (_met(not empty and not mismatched), len(verified),
                   len(empty), len(mismatched), len(missing)))
    rows.append("| licence coverage | %s — %d/%d fetched rows carry a licence "
                "(%d placeholder 'check') |"
                % (_met(present == nfetched), present, nfetched, placeholder))
    ck = ", ".join("%s %d" % (k, cc[k]) for k in sorted(cc)) or "empty"
    rows.append("| contrast classes populated | %s — %s |"
                % (_met(len(cc) >= CONTRAST_MIN), ck))
    rows.append("| negative_llm labelled | %s — %d rows, %d unlabelled |"
                % (_met(nllm > 0 and unlabelled == 0), nllm, unlabelled))
    rows.append("| splits doc-grouped; test publisher-held-out | %s — "
                "doc-grouped=%s, holdout=%s |"
                % (_met(grouped and holdout), grouped, holdout))
    rows.append("| no synthetic/unQA'd rows in val/test | %s — %d offending rows |"
                % (_met(dirty == 0), dirty))
    return rows


def carry_human_rows(old_text):
    """The two human-graded rows, verbatim from the live file, marked."""
    out = []
    lines = old_text.splitlines()
    for prefix, fallback in HUMAN_ROWS:
        line = fallback
        for l in lines:
            if l.strip().startswith(prefix):
                line = l.rstrip()
                break
        if HUMAN_MARK not in line:
            line = line.rstrip("|").rstrip() + " " + HUMAN_MARK + " |"
        out.append(line)
    return out


def tail_after_table(old_text):
    """Hand-written prose after the table, preserved verbatim."""
    lines = old_text.splitlines()
    last = -1
    for i, l in enumerate(lines):
        if l.lstrip().startswith("|"):
            last = i
    if last < 0:
        return []
    tail = lines[last + 1:]
    while tail and not tail[0].strip():
        tail.pop(0)
    while tail and not tail[-1].strip():
        tail.pop()
    return tail


def main():
    old = ""
    if os.path.isfile(STATE):
        with open(STATE) as f:
            old = f.read()
    out = HEADER + build_table() + carry_human_rows(old)
    tail = tail_after_table(old)
    if tail:
        out += [""] + tail
    text = "\n".join(out) + "\n"
    tmp = STATE + ".tmp"
    with open(tmp, "w") as f:
        f.write(text)
    os.replace(tmp, STATE)
    sys.stdout.write(text)
    sys.stderr.write("wrote %s\n" % os.path.relpath(STATE, ROOT))


if __name__ == "__main__":
    main()
